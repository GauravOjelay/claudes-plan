/**
 * Stylised world geometry for the 2D map. Shapes are deliberately rough (game art, not cartography).
 * All shapes are drawn in lon/lat and projected with `mapPosFromLonLat`, the same projection
 * that city `mapPos` values should use, so dots land on the right landmass.
 */
import type { RegionId } from '../contracts';

export const MAP_W = 1000;
export const MAP_H = 500;

/** lon/lat -> 0-1 map position (x: west->east, y: north->south). Fits the mock city positions. */
export function mapPosFromLonLat(lon: number, lat: number): { x: number; y: number } {
  return { x: (lon + 170) / 360, y: (93 - lat) / 150 };
}

type LonLat = [number, number];

function toPath(rings: LonLat[][]): string {
  return rings
    .map((ring) => {
      const pts = ring.map(([lon, lat]) => {
        const p = mapPosFromLonLat(lon, lat);
        return `${(p.x * MAP_W).toFixed(1)},${(p.y * MAP_H).toFixed(1)}`;
      });
      return `M${pts.join('L')}Z`;
    })
    .join('');
}

